#!/usr/bin/env python3
"""Highlight shoulders with unchanged exposure and a common gamma-code anchor.

200/400 denote compression strength, not a sensor dynamic range multiplier or EV gain.
The stock curve's premature white plateau is replaced before RGB LUT upload.
"""
import argparse
from bisect import bisect_left
from fractions import Fraction
import json
from pathlib import Path
from ep7_single_dr_gamma import GAMMA, ROM_POINTERS, WHITE
from ep7_single_dr_gamma import gamma_table as stock_gamma

KNEE_CODE = 2560
REFERENCE_CODE = 3968
COMPRESSION = (0, 168, 336)


def gamma_table(stock_image, stock_pointer, level):
    if level not in (0, 1, 2):
        raise ValueError('expected OFF/200/400')
    original = stock_gamma(stock_image, stock_pointer, 0)
    if not level:
        return original
    stock = GAMMA.unpack(original)
    knee = bisect_left(stock, KNEE_CODE)
    reference = bisect_left(stock, REFERENCE_CODE)
    span = len(stock) - 1 - knee
    start = stock[knee]
    rise = WHITE - start
    # Use the gentler of the adjacent native slopes at the join.
    entry_slope = min(start - stock[knee - 1], stock[knee + 1] - start)
    shoulder = span * entry_slope - rise
    t = Fraction(reference - knee, span)
    extra = stock[reference] - COMPRESSION[level] - start - rise * t
    if shoulder <= 0 or extra <= 0:
        raise ValueError('unsupported native shoulder')
    # Fit the rational shoulder to one near-white output code for every
    # native variant. A positive bend keeps the slope falling toward white.
    bend = (shoulder * t * (1 - t) / extra - 1) / t
    if bend <= 0 or rise - shoulder / (1 + bend) < span:
        raise ValueError('unsupported native shoulder')
    values = list(stock[:knee + 1])
    for step in range(1, span + 1):
        t = Fraction(step, span)
        values.append(round(start + rise * t + shoulder * t * (1 - t) / (1 + bend * t)))
    return GAMMA.pack(*values)


def inspect(stock_image):
    rows = []
    for variant, address in enumerate(dict.fromkeys(ROM_POINTERS), start=1):
        stock = GAMMA.unpack(gamma_table(stock_image, address, 0))
        knee = bisect_left(stock, KNEE_CODE)
        reference = bisect_left(stock, REFERENCE_CODE)
        first_white = stock.index(WHITE)
        previous = stock
        for level in (1, 2):
            values = GAMMA.unpack(gamma_table(stock_image, address, level))
            steps = [b - a for a, b in zip(values[knee:], values[knee + 1:])]
            if (values[:knee + 1] != stock[:knee + 1] or values[-1] != WHITE or
                    min(steps) <= 0 or stock[reference] - values[reference] != COMPRESSION[level] or
                    any(a > b for a, b in zip(values, previous))):
                raise ValueError('highlight-only curve contract failed')
            smallest_step = steps[0]
            for step in steps[1:]:
                if step > smallest_step + 1:  # One code of rounding tolerance.
                    raise ValueError('highlight shoulder steepens again')
                smallest_step = min(smallest_step, step)
            rows.append(dict(variant=variant, stock_pointer=hex(address), level=level,
                             unchanged_knots=f'0..{knee}', stock_white_knot=first_white,
                             mapped_white_knot=255,
                             reference_knot=reference, reference_stock_code=stock[reference],
                             compression_at_reference_12bit=stock[reference] - values[reference],
                             codes_after_stock_white=WHITE - values[first_white],
                             minimum_shoulder_step_12bit=smallest_step,
                             final_shoulder_step_12bit=steps[-1],
                             maximum_compression_12bit=max(a - b for a, b in zip(stock, values))))
            previous = values
    return rows


def target_table_source(stock_image):
    inspect(stock_image)
    lines = ['/* Generated by ep7_highlight_gamma.py; unchanged exposure. */',
             'static const struct gamma_row gamma_rows[] = {']
    for address in dict.fromkeys(ROM_POINTERS):
        lines.append(f'    {{0x{address:08x}u, {{')
        for level in (1, 2):
            values = GAMMA.unpack(gamma_table(stock_image, address, level))
            lines.append('        {')
            for start in range(0, 256, 16):
                lines.append('            ' + ', '.join(map(str, values[start:start+16])) + ',')
            lines.append('        },')
        lines.append('    }},')
    return '\n'.join([*lines, '};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('stock_main', type=Path)
    args = parser.parse_args()
    print(json.dumps(dict(strategy='highlight_mapping_only', tables=inspect(args.stock_main.read_bytes()),
                          physical_dynamic_range_measured=False), indent=2))
